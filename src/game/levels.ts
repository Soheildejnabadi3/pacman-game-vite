export const getLevelLayout = (level: number): CellType[][] => {
  const levelIndex = Math.min(level - 1, levels.length - 1);
  return levels[levelIndex].map(row => [...row]) as CellType[][];
};

export const countDots = (grid: CellType[][]): number => {
  let count = 0;
  for (const row of grid) {
    for (const cell of row) {
      if (cell === CellType.DOT || cell === CellType.POWER_PELLET) {
        count++;
      }
    }
  }
  return count;
};

export const findPacmanSpawn = (grid: CellType[][]): { x: number, y: number } => {
  for (let y = 0; y < grid.length; y++) {
    for (let x = 0; x < grid[y].length; x++) {
      if (grid[y][x] === CellType.PACMAN_SPAWN) {
        return { x, y };
      }
    }
  }
  return { x: 9, y: 15 }; // Default position if not found
};

export const findGhostSpawn = (grid: CellType[][]): { x: number, y: number } => {
  for (let y = 0; y < grid.length; y++) {
    for (let x = 0; x < grid[y].length; x++) {
      if (grid[y][x] === CellType.GHOST_SPAWN) {
        return { x, y };
      }
    }
  }
  return { x: 9, y: 9 }; // Default position if not found
};
